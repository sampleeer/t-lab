def prose_layout(text):
    blocks=text.split('\n\n')
    return '\n\n'.join(
        block if block.startswith(('#','|','```','- ','![')) else
        textwrap.fill(' '.join(block.splitlines()),width=96,break_long_words=False,break_on_hyphens=False)
        for block in blocks)


