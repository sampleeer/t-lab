def read(name): return json.loads((REPORT/name).read_text())


def groupname(name): return re.sub(r'_seed\d+','',name)


def md(data,digits=5):
    if not isinstance(data,pd.DataFrame): data=pd.DataFrame(data)
    def fmt(v):
        if isinstance(v,(float,np.floating)): return f'{v:.{digits}f}'
        return str(v).replace('|','/')
    return '\n'.join(['| '+' | '.join(map(str,data.columns))+' |','| '+' | '.join(['---']*len(data.columns))+' |']+
       ['| '+' | '.join(fmt(v) for v in row)+' |' for row in data.itertuples(index=False,name=None)])


def grouped(metrics,endpoint=False):
    d=pd.DataFrame(metrics).T
    d=d.loc[[n for n in d.index if n.endswith('_endpoint')==endpoint or n=='colab_sft']]
    d['group']=[groupname(n) for n in d.index]
    return d.groupby('group',sort=False).mean(numeric_only=True)


