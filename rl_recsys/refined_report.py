def trajectory_tables():
    allrows=[]; ci={}
    lock=read('selection.json')
    for split in ('test','extra'):
        user_tables={}
        for variant in lock['models']:
            name=variant['name']; d=pd.read_csv(REPORT/f'{split}_{name}_rollouts.csv')
            discount=.95**(d.step-1)
            d['fraction_return']=discount*d.pred_fraction
            d['seconds_return']=discount*d.pred_seconds
            d['balanced_return']=discount*d.balanced
            user=d.groupby(['user','event'])[['fraction_return','seconds_return','balanced_return']].sum().groupby('user').mean()
            user_tables[name]=user
            last=d.loc[d.step==5].groupby('user').mean(numeric_only=True)
            row={'split':split,'model':name,**user.mean().to_dict(),
                 'repeat_generated_step5':float(last.repeat_generated.mean()),
                 'repeat_original_step5':float(last.repeat_original.mean()),
                 'fraction_drift_step5':float((last.pred_fraction-last.frozen_fraction).mean()),
                 'reference_nll_drift_step5':float((last.sft_nll-last.frozen_sft_nll).mean()),'users':len(user)}
            allrows.append(row)
        rng=np.random.default_rng(42); comparisons={}
        for seed in (42,2026):
            a=user_tables[f'balanced_h1_seed{seed}']; b=user_tables[f'balanced_h5_seed{seed}']
            dif=b.balanced_return-a.balanced_return
            bs=dif.to_numpy()[rng.integers(0,len(dif),(2000,len(dif)))].mean(1)
            comparisons[f'balanced_h5_minus_h1_seed{seed}']={'delta':float(dif.mean()),
                     'lower95':float(np.quantile(bs,.025)),'upper95':float(np.quantile(bs,.975)),'users':len(dif)}
        ci[split]=comparisons
    table=pd.DataFrame(allrows); table.to_csv(REPORT/'trajectory_returns.csv',index=False)
    dump(REPORT/'trajectory_intervals.json',ci)
    return table,ci


